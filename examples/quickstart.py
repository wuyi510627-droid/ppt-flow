from common import *

sl = cover('PPT Flow · 图解汇报示例', '示例', presenter='示例汇报人')
notes(sl, '约 15 秒：本示例演示如何用时间线和两条路径讲清楚一个问题。地址是虚构教学案例。')

sl = newslide('同一次搬家，问题时间决定答案', '01 · 场景与问题')
flow(sl, 65, 160, [('周一', '住在 A'), ('周三', '搬到 B'), ('周五', '填写地址')],
     w=235, h=105, gap=60, col=[BLUE, PURPLE, BROWN], tsz=26, dsz=21)
box(sl, 110, 330, 310, 90, [([R('问现在：B', 26, GREEN, True)], 0)], fill=GL, line=GREEN)
box(sl, 540, 330, 310, 90, [([R('问搬家前：A', 26, BLUE, True)], 0)], fill=BL, line=BLUE)
notes(sl, '约 45 秒：从左到右讲时间线。周一住 A，周三搬到 B，周五收到填单请求。问当前地址应填写 B；问搬家前则回答 A。讲解的重点是先确定问题对应的时间。')

sl = newslide('少量要点自动带入，详细记录按需查找', '02 · 两条使用路径')
flow(sl, 65, 170, [('关键要点', '当前地址与生效时间'), ('开场加载', '直接进入输入'), ('当前任务', '结合问题使用')],
     w=235, h=95, gap=60, col=GREEN, tsz=22, dsz=18)
flow(sl, 65, 340, [('完整记录', '保留历史与原始依据'), ('按需查找', '需要细节时读取'), ('补充证据', '回答历史问题')],
     w=235, h=95, gap=60, col=BLUE, tsz=22, dsz=18)
notes(sl, '约 1 分钟：先讲上方路径，少量关键要点在开场进入输入。再讲下方路径，完整记录保留在资料中，需要时查找。两条路径配合使用。这是教学示意，不对应特定论文的完整实现。')

